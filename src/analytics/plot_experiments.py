import os
import re
import matplotlib.pyplot as plt

def generate_privacy_tradeoff_plot(log_path: str, out_path: str):
    if not os.path.exists(log_path):
        print(f"Skipping DP trade-off: {log_path} not found.")
        return

    epsilons = []
    maes = []
    
    with open(log_path, 'r') as f:
        # Regex to match the sweep table: 0.01  | 100.50
        # Looking ONLY in the section [B] sweep after the header line
        in_sweep = False
        for line in f:
            if "[B] Sweeping Privacy Budgets" in line:
                in_sweep = True
                continue
            if in_sweep:
                pattern = re.compile(r"^\s*([0-9\.]+)\s*\|\s*([0-9\.]+)\s*$")
                match = pattern.match(line)
                if match:
                    epsilons.append(float(match.group(1)))
                    maes.append(float(match.group(2)))

    if not epsilons:
        print("No DP sweep data found in log.")
        return

    plt.figure(figsize=(10, 6))
    plt.plot(epsilons, maes, marker='o', linestyle='-', color='#d62728', linewidth=2.5)
    plt.xscale('log')
    plt.yscale('log')
    
    plt.title("Differential Privacy: Epsilon budget vs. Statistical Noise", fontsize=14, pad=20)
    plt.xlabel("Privacy Budget (\u03b5) [Log Scale]", fontsize=12)
    plt.ylabel("Mean Absolute Error (Data Utility Loss)", fontsize=12)
    plt.grid(True, which="both", ls="-", alpha=0.2)
    plt.axvline(x=1.0, color='gray', linestyle='--', alpha=0.5, label='Standard Balance (\u03b5=1)')
    plt.legend()
    plt.tight_layout()
    plt.savefig(out_path, dpi=300)
    print(f"Generated DP Pareto Trade-off Curve: {out_path}")

def generate_cms_tradeoff_plot(log_path: str, out_path: str):
    if not os.path.exists(log_path):
        print(f"Skipping CMS trade-off: {log_path} not found.")
        return

    widths = []
    errors = []
    
    with open(log_path, 'r') as f:
        # Regex to match: 100  | 2000  | 50.25 (Width | Mem | Avg Err)
        in_sweep = False
        for line in f:
            if "[C] Sweeping CMS Width" in line:
                in_sweep = True
                continue
            if in_sweep:
                match = re.search(r"^\s*(\d+)\s*\|\s*\d+\s*\|\s*([0-9\.]+)\s*$", line)
                if match:
                    widths.append(int(match.group(1)))
                    errors.append(float(match.group(2)))

    if not widths:
        print("No CMS sweep data found in log.")
        return

    plt.figure(figsize=(10, 6))
    # We use width*5*4 for memory in bytes
    memory_kb = [(w * 5 * 4)/1024.0 for w in widths]
    
    plt.plot(memory_kb, errors, marker='s', linestyle='--', color='#2ca02c', linewidth=2.5)
    
    plt.title("Count-Min Sketch: Space vs. Accuracy Trade-off", fontsize=14, pad=20)
    plt.xlabel("Memory Space Used (Kilobytes)", fontsize=12)
    plt.ylabel("Average Estimation Error (MAE)", fontsize=12)
    plt.yscale('log')
    plt.grid(True, which="both", alpha=0.3)
    plt.tight_layout()
    plt.savefig(out_path, dpi=300)
    print(f"Generated CMS Space/Accuracy Curve: {out_path}")

